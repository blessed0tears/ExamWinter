-- Создание базы данных
CREATE DATABASE IF NOT EXISTS ExamWinter;
USE ExamWinter;

-- Таблица Role
CREATE TABLE IF NOT EXISTS Role (
    RoleId INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(100) NOT NULL
);

-- Таблица User
CREATE TABLE IF NOT EXISTS User (
    UserId INT AUTO_INCREMENT PRIMARY KEY,
    RoleId INT NOT NULL,
    Surname VARCHAR(100) NOT NULL,
    Name VARCHAR(100) NOT NULL,
    Patronymic VARCHAR(100) NOT NULL,
    Login VARCHAR(255) NOT NULL,
    Password VARCHAR(255) NOT NULL,
    FOREIGN KEY (RoleId) REFERENCES Role(RoleId)
);

-- Таблица PickupPoint
CREATE TABLE IF NOT EXISTS PickupPoint (
    PickupPointId INT AUTO_INCREMENT PRIMARY KEY,
    `Index` INT NOT NULL,
    City VARCHAR(100) NOT NULL,
    Street VARCHAR(100) NOT NULL,
    HomeNumber TINYINT NOT NULL
);

-- Таблица Product
CREATE TABLE IF NOT EXISTS Product (
    ProductId INT AUTO_INCREMENT PRIMARY KEY,
    ArticleNumber VARCHAR(100) NOT NULL,
    Name TEXT NOT NULL,
    Description TEXT NOT NULL,
    Category TEXT NOT NULL,
    Photo TEXT NULL,
    Manufacturer TEXT NOT NULL,
    Cost DECIMAL(19,4) NOT NULL,
    DiscountAmount TINYINT NULL,
    QuantityInStock INT NOT NULL,
    Status TEXT NOT NULL
);

-- Таблица Order
CREATE TABLE IF NOT EXISTS `Order` (
    OrderId INT AUTO_INCREMENT PRIMARY KEY,
    UserId INT NULL,
    PickupPointId INT NOT NULL,
    Status TEXT NOT NULL,
    Date DATETIME NOT NULL,
    DeliveryDate DATETIME NOT NULL,
    PickupCode INT NOT NULL,
    FOREIGN KEY (UserId) REFERENCES User(UserId),
    FOREIGN KEY (PickupPointId) REFERENCES PickupPoint(PickupPointId)
);

-- Таблица OrderProduct
CREATE TABLE IF NOT EXISTS OrderProduct (
    OrderId INT NOT NULL,
    ProductId INT NOT NULL,
    Amount SMALLINT NOT NULL,
    PRIMARY KEY (OrderId, ProductId),
    FOREIGN KEY (OrderId) REFERENCES `Order`(OrderId),
    FOREIGN KEY (ProductId) REFERENCES Product(ProductId)
);

